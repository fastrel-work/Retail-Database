-- Problem 5: Identify the Product Categories That Generate the Most Profit
-- Business Question:
-- Which product categories generate the highest total profit for the company?
--
-- Goal:
-- Connect order-detail records to their products and product categories, calculate
-- the profit generated from sales, and group those profits by category.
--
-- Profit Formula:
--
-- Profit per Unit = UnitPrice - UnitCost
--
-- Profit per Line Item = Quantity × (UnitPrice - UnitCost)
--
-- Total Category Profit = SUM(Quantity × (UnitPrice - UnitCost))


SELECT
    c.CatagoryName,

    -- Retrieves the name of each product category from the catagories table.
    --
    -- The "c." prefix specifies that CatagoryName comes from the table assigned
    -- the alias "c".


    SUM(od.Quantity * (od.UnitPrice - od.UnitCost)) AS total_profit

    -- od.UnitPrice - od.UnitCost calculates the profit generated from ONE unit.
    
    -- Multiplying the profit per unit by Quantity calculates the profit generated
    -- by the entire order-detail record.
    
    -- SUM(...) adds together the profit from all order-detail records belonging
    -- to products within the same category.

    -- AS total_profit assigns a descriptive alias to the calculated output column.


FROM order_details AS od

    -- Begins with the order_details table because it contains the values required
    -- for the profit calculation:
    --
    -- Product_ID
    -- Quantity
    -- UnitPrice
    -- UnitCost
    --
    -- AS od assigns "od" as a temporary alias for the order_details table.


JOIN products AS p
    ON od.Product_ID = p.Product_ID

    -- Connects each order-detail record to its corresponding product using Product_ID.
    --
    -- The products table contains the Catagory_ID associated with each product.
    --
    -- This connection is necessary because order_details does not directly contain
