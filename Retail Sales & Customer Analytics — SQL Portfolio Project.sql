-- =================================================================================================
-- Problem 3: Identify the Highest-Revenue Customers
-- Business Question:
-- Which customers generate the most gross sales revenue for the company?
--
-- Goal:
-- Calculate total gross revenue for each customer and rank customers from the
-- highest revenue generator to the lowest.
--
-- Revenue Formula:
-- Revenue per Line Item = Quantity × UnitPrice
--
-- Customer Revenue = SUM(Quantity × UnitPrice) for all purchases made by that customer


SELECT
    c.Customer_ID,

    -- Retrieves the Customer_ID so each customer can be identified in the result.
    --
    -- The "c." prefix specifies that Customer_ID is being retrieved from the
    -- customers table, which has been assigned the alias "c".


    SUM(od.Quantity * od.UnitPrice) AS total_revenue

    -- Quantity * UnitPrice calculates the gross revenue generated by each
    -- individual order-detail record.
    --
    -- SUM(...) adds together the revenue from all order-detail records
    -- associated with the same customer.


FROM customers AS c

    -- Begins with the customers table.
    -- AS c assigns "c" as a temporary alias for easier reference.


JOIN orders AS o
    ON c.Customer_ID = o.Customer_ID

    -- Connects customers to their orders using Customer_ID.
    --
    -- Customer_ID represents the same customer in both tables, allowing SQL
    -- to determine which orders belong to each customer.


JOIN order_details AS od
    ON od.Order_ID = o.Order_ID

    -- Connects each order to its corresponding order-detail records using Order_ID.
    --
    -- The orders table acts as the bridge between customers and order_details:
    --
    -- customers → orders → order_details
    --
    -- This allows the Quantity and UnitPrice values from each purchase to be
    -- associated with the customer who placed the order.


GROUP BY c.Customer_ID

    -- GROUP BY places all records belonging to the same customer into one group.
    --
    -- SUM(Quantity * UnitPrice) is then calculated separately for each customer.
    --
    -- This transforms multiple purchase records into one summarized revenue
    -- result for each customer.


ORDER BY total_revenue DESC;

    -- ORDER BY determines how the final result set is sorted.
    --
    -- total_revenue refers to the alias created earlier for:
    --
    -- SUM(od.Quantity * od.UnitPrice)
    --
    -- DESC means "descending," which sorts numerical values from highest to lowest.
    --
    -- Therefore, the customer generating the most revenue appears at the top
    -- of the result set, followed by the next highest-revenue customer, and so on.
    --
    -- ASC (ascending) would do the opposite and sort from lowest to highest.



-- Interpretation:
-- Based on gross revenue, CSTMR0127 is the highest-revenue customer in the dataset,
-- generating $3,396.19 in sales.



-- Important:
-- This query ranks customers by GROSS REVENUE, not by profit.
--
-- Discounts are not deducted because DiscountRate is not included in the calculation,
-- and product costs are not deducted because UnitCost is not included.
--
-- Therefore, a customer appearing near the top generated a large amount of sales,
-- but this does not necessarily mean they were one of the company's most profitable
-- customers.
-- =================================================================================================



-- =================================================================================================
-- Problem 4: Identify the Products That Generate the Most Profit
-- Business Question:
-- Which products generate the highest total profit for the company?
--
-- Goal:
-- Calculate the profit generated by each product across all order-detail records,
-- display the corresponding product name, and rank products from highest to lowest profit.
--
-- Profit Formula:
--
-- Profit per Unit = UnitPrice - UnitCost
--
-- Profit per Line Item = Quantity × (UnitPrice - UnitCost)
--
-- Total Product Profit = SUM(Quantity × (UnitPrice - UnitCost))




SELECT
    od.Product_ID,

    -- Retrieves the Product_ID from the order_details table.
    --
    -- Product_ID uniquely identifies which product is associated with each
    -- order-detail record.


    p.ProductName,

    -- Retrieves the corresponding product name from the products table.
    --
    -- ProductName makes the final result easier to interpret than displaying
    -- only the Product_ID.


    SUM(od.Quantity * (od.UnitPrice - od.UnitCost)) AS total_profit

    -- od.UnitPrice - od.UnitCost calculates the profit earned from ONE unit.
    
    -- The result is then multiplied by Quantity to calculate the profit
    -- generated by the entire order-detail record.
    
    -- SUM(...) adds together the profit from every order-detail record
    -- associated with the same product.
 
    -- AS total_profit assigns a descriptive alias to the calculated column.


FROM order_details AS od

    -- Begins with the order_details table because it contains the values needed
    -- for the profit calculation:
    --
    -- Product_ID
    -- Quantity
    -- UnitPrice
    -- UnitCost
    --
    -- AS od assigns "od" as a temporary alias for the order_details table.


JOIN products AS p
    ON od.Product_ID = p.Product_ID

    -- Connects order_details to the products table using Product_ID.
    --
    -- Product_ID represents the same product in both tables:
    --
    -- order_details.Product_ID = identifies the product purchased
    -- products.Product_ID      = identifies the product and its descriptive information
    --
    -- This JOIN allows the ProductName stored in the products table to be displayed
    -- alongside the sales and profit information stored in order_details.


GROUP BY od.Product_ID, p.ProductName

    -- GROUP BY places all order-detail records belonging to the same product
    -- into a group.
    --
    -- SUM(...) then calculates total profit separately for each product.
    --
    -- Both Product_ID and ProductName are included because they appear in the
    -- SELECT statement without being inside an aggregate function such as SUM().


ORDER BY total_profit DESC;

    -- ORDER BY sorts the completed product-level results using total_profit.


-- Interpretation:
-- Based on this profit calculation, ABC's Ground Beef generated the highest
-- total profit in the dataset at approximately $14,438.44.
--
-- Ranking products by total profit helps identify which products contribute
-- the greatest amount of gross profit to the business.


-- Important:
-- This calculation is different from the revenue calculations used previously.
--
-- Revenue:
-- Quantity × UnitPrice
--
-- Profit used in this analysis:
-- Quantity × (UnitPrice - UnitCost)
--
-- Revenue measures how much money is generated from sales, while this profit
-- calculation also accounts for the recorded cost of the products sold.
--
-- However, this is a simplified product-level gross profit calculation.
-- It does not account for discounts, returns, taxes, shipping, labor,
-- overhead, or other operating expenses.
--
-- Therefore, "total_profit" in this query should not be interpreted as the
-- company's final net profit.
-- =================================================================================================



