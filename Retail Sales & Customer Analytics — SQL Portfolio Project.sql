-- Problem 7: Analyze Month-over-Month Revenue Growth
-- Business Question:
-- How is the company's gross sales revenue changing from month to month?
-- Are monthly sales increasing or decreasing compared with the previous month?
--
-- Goal:
-- 1. Calculate total gross revenue for each month.
-- 2. Retrieve the previous month's revenue.
-- 3. Compare the current month with the previous month.
-- 4. Calculate the percentage increase or decrease in revenue.
--
-- Revenue Formula:
-- Monthly Revenue = SUM(Quantity × UnitPrice)
--
-- Month-over-Month (MoM) Growth Formula:
--
--                         Current Month Revenue - Previous Month Revenue
-- Growth Percentage =    ------------------------------------------------ × 100
--                                   Previous Month Revenue


-- Step 1: Create a Common Table Expression (CTE) containing monthly revenue.

WITH monthly_sales AS (

    -- WITH creates a Common Table Expression (CTE).
    --
    -- A CTE can be thought of as a temporary named result set that exists only
    -- while this query is running.
    --
    -- The name "monthly_sales" allows the monthly revenue results calculated
    -- below to be referenced by the final SELECT statement.


    SELECT
        DATE_FORMAT(o.OrderDate, '%Y-%m') AS month,

        -- DATE_FORMAT() converts each OrderDate into a Year-Month format.
        --
        -- Using '%Y-%m' preserves both the year and month.
        --
        -- This is important because grouping only by the month number could
        -- incorrectly combine the same month from different years.
        --
        -- AS month assigns a readable alias to the formatted date.


        SUM(od.Quantity * od.UnitPrice) AS monthly_revenue

        -- Quantity * UnitPrice calculates gross revenue for each order-detail record.
        --
        -- SUM(...) adds together all revenue associated with orders occurring
        -- within the same month.
        --
        -- Because the records are grouped by Year-Month below, SQL calculates
        -- one gross revenue total for each month.
        --
        -- AS monthly_revenue assigns a descriptive alias to the calculated result.


    FROM orders AS o

        -- Begins with the orders table because it contains OrderDate, which is
        -- necessary to determine when each sale occurred.


    JOIN order_details AS od
        ON o.Order_ID = od.Order_ID

        -- Connects each order to its corresponding order-detail records using Order_ID.
        --
        -- The orders table provides the date of the transaction, while order_details
        -- provides Quantity and UnitPrice.
     


    GROUP BY DATE_FORMAT(o.OrderDate, '%Y-%m')

        -- GROUP BY places all orders occurring within the same Year-Month
        -- into the same group.
        --
        -- SUM(Quantity * UnitPrice) is then calculated separately for each month.


)


-- Step 2: Compare each month's revenue with the previous month.

SELECT
    month,

    -- Displays the Year-Month created inside the monthly_sales CTE.


    monthly_revenue,

    -- Displays the total gross revenue calculated for the current month.


    LAG(monthly_revenue) OVER (ORDER BY month) AS previous_month_revenue,

    -- LAG() is a window function that retrieves a value from a previous row
    -- without removing or combining the current rows.
    --
    -- In this case:
    --
    -- LAG(monthly_revenue)
    --
    -- asks SQL to retrieve the monthly_revenue value from the previous row.
    --
    -- OVER (ORDER BY month) tells SQL how the rows should be arranged before
    -- determining which row counts as the "previous" row.
    


    ROUND(
        (
            monthly_revenue
            - LAG(monthly_revenue) OVER (ORDER BY month)
        )
        /
        LAG(monthly_revenue) OVER (ORDER BY month)
        * 100,
        2
    ) AS growth_percentage

    -- This calculation determines the percentage change in revenue between
    -- the current month and the previous month.
    --
    -- Step 1:
    -- Current Revenue - Previous Revenue
    --
    -- This determines the dollar change between the two months.
    --
    -- Step 2:
    -- Divide the change by the PREVIOUS month's revenue:
    --
    -- Step 3:
    -- Multiply by 100 to convert the decimal into a percentage:
    --
    -- ROUND(..., 2) rounds the final percentage to two decimal places.
    --
    -- AS growth_percentage assigns a descriptive alias to the calculated result.


FROM monthly_sales;

    -- The final SELECT retrieves its data from the monthly_sales CTE rather
    -- than directly from the original tables.
    --
    -- At this stage, monthly_sales already contains one row per month, making
    -- it easier to compare each month's revenue with the previous month.




-- Important:
-- This query calculates GROSS revenue because it uses:
--
-- Quantity × UnitPrice
--
-- Discounts, product costs, returns, and other expenses are not included.
--
-- Therefore, growth_percentage measures the month-over-month percentage change
-- in gross sales revenue, not profit.
-- =================================================================================================



