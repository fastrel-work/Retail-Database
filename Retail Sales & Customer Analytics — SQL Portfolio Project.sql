-- Problem 8: Identify the Most Valuable Repeat Customers
-- Business Question:
-- Which customers have purchased from the company more than once, and which of those
-- repeat customers generated the most gross revenue?
--
-- Goal:
-- 1. Count the number of unique orders placed by each customer.
-- 2. Calculate the total gross revenue generated by each customer.
-- 3. Keep only customers who placed more than one order.
-- 4. Rank those repeat customers from highest to lowest revenue.
--
-- Repeat Customer Definition:
-- A repeat customer is defined in this analysis as a customer who has placed
-- more than one distinct order.
--
-- Revenue Formula:
-- Customer Revenue = SUM(Quantity × UnitPrice)



SELECT
    o.Customer_ID,

    -- Retrieves the Customer_ID associated with each order.
    --
    -- Customer_ID identifies which customer placed each order.
    --
    -- Because the query will later GROUP BY Customer_ID, the final result
    -- will contain one summarized row for each repeat customer.


    COUNT(DISTINCT o.Order_ID) AS total_orders,

    -- COUNT() counts values within each customer's group.
    --
    -- DISTINCT tells SQL to count each Order_ID only once.
    --
    -- This is especially important because joining orders to order_details
    -- can cause the same Order_ID to appear multiple times.
    
    -- AS total_orders assigns a descriptive alias to the calculated column.


    SUM(od.Quantity * od.UnitPrice) AS total_revenue

    -- Quantity * UnitPrice calculates the gross revenue generated by each
    -- individual order-detail record.
    --
    -- SUM(...) then adds together the revenue from all order-detail records
    -- associated with the same customer.
    --
    -- AS total_revenue assigns a descriptive alias to the calculated column.


FROM orders AS o

    -- Begins with the orders table.
    --
    -- The orders table contains both Customer_ID and Order_ID, allowing the query
    -- to determine which orders belong to each customer.
    --
    -- AS o assigns "o" as a temporary alias for the orders table.


JOIN order_details AS od
    ON od.Order_ID = o.Order_ID

    -- Connects each order to its corresponding order-detail records using Order_ID.
    --
    -- The orders table provides the customer associated with each order.
    -- The order_details table provides the Quantity and UnitPrice needed to
    -- calculate revenue.
    --
    -- Together, the relationship allows SQL to determine:
    --
    -- Customer → Order → Purchases → Revenue


GROUP BY o.Customer_ID

    -- GROUP BY places all records belonging to the same customer into one group.
    --
    -- The aggregate functions are then calculated separately for each customer:
    --
    -- COUNT(DISTINCT Order_ID) → Number of unique orders
    -- SUM(Quantity * UnitPrice) → Total gross revenue
    

HAVING COUNT(DISTINCT o.Order_ID) > 1

    -- HAVING filters the results AFTER the records have been grouped.
    --
    -- This condition keeps only customers who placed more than one
    -- distinct order.
    --
    -- HAVING is used instead of WHERE because total_orders is based on
    -- an aggregate calculation: COUNT(DISTINCT Order_ID).
    --
    -- SQL must first group the records and count each customer's orders
    -- before it can determine whether that customer has more than one order.


ORDER BY total_revenue DESC;

    -- ORDER BY sorts the remaining repeat customers according to total_revenue.
    --
    -- DESC means descending order, so the repeat customer who generated the
    -- highest gross revenue appears first.
    --
    -- This allows the analysis to identify not only who purchased repeatedly,
    -- but also which repeat customers contributed the most revenue.



-- Interpretation:
-- CSTMR0127 generated the highest gross revenue among the repeat customers
-- identified by this query, producing approximately $3,396.19 across 11 orders.
--
-- The results also demonstrate that purchase frequency and revenue do not
-- necessarily move together.
--
-- CSTMR0104 placed more orders, but CSTMR0127 generated more total revenue.
--
-- This means that simply having the highest number of orders does not necessarily
-- make a customer the highest-revenue customer. Order values also matter.


-- Important:
-- This query defines a repeat customer specifically as someone who has placed
-- more than ONE distinct order.
--
-- COUNT(DISTINCT Order_ID) is important because the JOIN with order_details can
-- create multiple rows for a single order when that order contains multiple products.
