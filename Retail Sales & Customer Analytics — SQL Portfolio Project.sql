-- Problem 10: Calculate the Percentage of Revenue Generated by the Top 10% of Customers
-- Business Question:
-- What percentage of the company's total gross revenue is generated by its
-- highest-revenue customers?
--
-- Goal:
-- 1. Calculate total gross revenue generated by each customer.
-- 2. Rank customers from highest to lowest revenue.
-- 3. Select the top 100 customers.
-- 4. Calculate the combined revenue generated by those customers.
-- 5. Compare their combined revenue with total company revenue.
-- 6. Express the result as a percentage.
--
-- Dataset Assumption:
-- The dataset contains 1,000 customers.
--
-- Therefore:
--
-- 1,000 × 10% = 100 customers
--
-- Selecting the top 100 customers represents the top 10% of customers
-- in this specific dataset.
--
-- Revenue Formula:
-- Customer Revenue = SUM(Quantity × UnitPrice)
--
-- Revenue Share Formula:
--
--                         Revenue from Top 100 Customers
-- Top 10% Revenue Share = -------------------------------- × 100
--                              Total Company Revenue



-- Step 1: Create a CTE containing the 100 highest-revenue customers.

WITH top_customers AS (

    -- WITH creates a Common Table Expression (CTE).
    --
    -- The CTE creates a temporary named result set called "top_customers"
    -- that can be referenced by the main query below.
    --
    -- This CTE will contain only the 100 customers who generated the
    -- highest amount of gross revenue.


    SELECT
        o.Customer_ID,

        -- Retrieves the Customer_ID associated with each order.
        --
        -- Customer_ID will later be used to group all purchases belonging
        -- to the same customer.


        SUM(od.Quantity * od.UnitPrice) AS total_revenue

        -- Quantity * UnitPrice calculates gross revenue for each
        -- individual order-detail record.
        --
        -- SUM(...) adds together all order-detail revenue belonging
        -- to the same customer.
        --
        -- AS total_revenue assigns a descriptive alias to the calculation.


    FROM orders AS o

        -- Begins with the orders table because it contains Customer_ID,
        -- which identifies the customer who placed each order.


    JOIN order_details AS od
        ON od.Order_ID = o.Order_ID

        -- Connects each order to its corresponding order-detail records
        -- using Order_ID.
        --
        -- The orders table tells us WHICH CUSTOMER placed the order.
        --
        -- The order_details table provides Quantity and UnitPrice,
        -- which are needed to calculate revenue.
        --
        -- Together:
        --
        -- Customer → Order → Order Details → Revenue


    GROUP BY o.Customer_ID

        -- GROUP BY places all order-detail records belonging to the same
        -- customer into one group.
        --
        -- SUM(Quantity * UnitPrice) is then calculated separately
        -- for each customer.


    ORDER BY total_revenue DESC

        -- ORDER BY sorts customers according to total revenue.
        --
        -- DESC means descending order, so the highest-revenue customer
        -- appears first.
        --
        -- This sorting is necessary because LIMIT 100 will select the
        -- first 100 customers from this ranked result.


    LIMIT 100

        -- LIMIT 100 keeps only the first 100 customers after the results
        -- have been sorted from highest to lowest revenue.
        --
        -- Since this dataset contains 1,000 customers:
        --
        -- 100 / 1,000 × 100 = 10%
        --
        -- Therefore, these 100 customers represent the top 10% of customers
        -- based on gross revenue generated.

)


-- Step 2: Calculate what percentage of total company revenue comes
-- from the top 100 customers.

SELECT
    ROUND(
        SUM(total_revenue)
        /
        (
            SELECT SUM(Quantity * UnitPrice)
            FROM order_details
        )
        * 100,
        2
    ) AS top_10_percent_revenue_share

    -- SUM(total_revenue) adds together the revenue generated by all
    -- 100 customers stored inside the top_customers CTE.
    --
    -- In this dataset:
    --
    -- Top 100 Customer Revenue = approximately $209,472.99
    --
    -- This becomes the NUMERATOR of the percentage calculation.
    --
    --
    -- The subquery:
    --
    -- (
    --     SELECT SUM(Quantity * UnitPrice)
    --     FROM order_details
    -- )
    --
    -- independently calculates total gross revenue generated by the
    -- entire company across all order-detail records.
    --
    -- In this dataset:
    --
    -- Total Company Gross Revenue = approximately $791,932.47
    --
    -- This becomes the DENOMINATOR.
    --
    -- Therefore, the calculation is approximately:
    --
    -- $209,472.99
    -- ----------- × 100
    -- $791,932.47
    --
    -- ≈ 26.45%
    --
    -- ROUND(..., 2) rounds the final percentage to two decimal places.
    --
    -- AS top_10_percent_revenue_share assigns a descriptive name
    -- to the final calculated result.


FROM top_customers;

    -- The outer query retrieves its numerator from the top_customers CTE.
    --
    -- Since the CTE contains only the 100 highest-revenue customers,
    -- SUM(total_revenue) represents the combined gross revenue generated
    -- by the top 10% of customers.


-- Final Result:
--
-- top_10_percent_revenue_share
-- -----------------------------
--             26.45
--
-- The top 10% of customers generated approximately 26.45% of the
-- company's total gross revenue represented in this dataset.


-- Interpretation:
-- Although the top 100 customers represent only 10% of the 1,000 customers,
-- they account for approximately 26.45% of total gross revenue.
--
-- This indicates that revenue is not distributed evenly across customers.
-- The highest-revenue 10% contribute a disproportionately larger share
-- of total gross sales.
--
-- This information could be useful for customer segmentation, retention
-- analysis, loyalty programs, and understanding how dependent the business
-- is on its highest-revenue customers.


-- Important:
-- This analysis ranks customers using GROSS REVENUE:
--
-- Quantity × UnitPrice
--
-- It does not account for:
--
-- • Discounts
-- • Product costs
-- • Returns
-- • Shipping expenses
-- • Taxes
-- • Other operating expenses
--
-- Therefore, the result represents the top customers by gross sales revenue,
-- not necessarily the company's most profitable customers.


-- Important:
