-- Problem 9: Identify Customers Who May Be Becoming Inactive
-- Business Question:
-- Which customers have not made a purchase recently and may be becoming inactive?
--
-- Goal:
-- 1. Find each customer's most recent purchase date.
-- 2. Calculate how many days have passed since that purchase.
-- 3. Identify customers whose most recent purchase was more than 180 days before
--    the latest date represented in the dataset.
-- 4. Rank those customers from longest inactive period to shortest.
--
-- Inactivity Definition:
-- For this analysis, a customer is considered potentially inactive if their
-- most recent purchase occurred more than 180 days before 2026-06-01.
--
-- Reference Date:
-- 2026-06-01 is used because it is the latest OrderDate in this dataset.
-- Using the dataset's latest date keeps the analysis aligned with the period
-- represented by the data rather than comparing historical data with today's date.


SELECT
    Customer_ID,

    -- Retrieves the Customer_ID from the orders table.
    --
    -- Because the query will later GROUP BY Customer_ID, the final result
    -- will contain one summarized row for each customer who meets the
    -- inactivity condition.


    MAX(OrderDate) AS last_purchase_date,

    -- A customer may have multiple orders and therefore multiple OrderDate values.
    --
    -- MAX(OrderDate) finds the latest (most recent) OrderDate for each customer.
    --
    -- With dates, MAX() returns the greatest/latest date.
    --
    -- AS last_purchase_date assigns a descriptive alias to the calculated result.


    DATEDIFF('2026-06-01', MAX(OrderDate)) AS days_since_last_purchase

    -- DATEDIFF() calculates the number of days between two dates.
    --
    -- Syntax:
    --
    -- DATEDIFF(later_date, earlier_date)
    --
    -- In this query:
    --
    -- Later Date   = 2026-06-01
    -- Earlier Date = Customer's most recent OrderDate
    --
    -- SQL therefore calculates:
    --
    -- 2026-06-01 - last_purchase_date
    --
    -- Example:
    --
    -- Reference Date       = 2026-06-01
    -- Last Purchase Date   = 2025-11-10
    --
    -- DATEDIFF determines how many days passed between those dates.
    --
    -- A larger number means the customer has gone a longer period without
    -- making another purchase.
    --
    -- AS days_since_last_purchase assigns a descriptive alias to this calculation.


FROM orders

    -- The orders table contains all information required for this analysis:
    --
    -- Customer_ID = identifies who placed the order.
    -- OrderDate    = identifies when the order was placed.
    --
    -- No JOIN is necessary because both required columns are already stored
    -- in the same table.


GROUP BY Customer_ID

    -- GROUP BY places all orders belonging to the same customer into one group.
    --
    -- MAX(OrderDate) is then calculated separately for each customer.
    --
    -- SQL has reduced multiple orders per customer into one record showing
    -- each customer's most recent purchase.


HAVING DATEDIFF('2026-06-01', MAX(OrderDate)) > 180

    -- HAVING filters the customer groups after MAX(OrderDate) has been calculated.
    --
    -- The query keeps only customers whose most recent purchase occurred
    -- more than 180 days before the reference date.
    --
    -- HAVING is appropriate because the condition depends on MAX(OrderDate),
    -- which is an aggregate calculation performed for each customer group.


ORDER BY days_since_last_purchase DESC;

    -- ORDER BY sorts the remaining customers according to the number of days
    -- since their most recent purchase.
    --
    -- DESC means descending order, so the largest number appears first.
    --
    -- Therefore, customers who have gone the longest without purchasing
    -- appear at the top of the result.
    --
    -- This makes the customers with the longest periods of inactivity
    -- immediately visible.


-- Final Result:
-- The query returns customers whose most recent purchase was more than
-- 180 days before the dataset's reference date.
--
-- The customers are ranked from the longest period without a purchase
-- to the shortest period that still exceeds the 180-day threshold.


-- Interpretation:
-- Customers appearing in this result have gone more than approximately
-- six months without making another purchase as of 2026-06-01.
--
-- Customers near the top of the result have gone the longest without
-- purchasing and may warrant further investigation for possible inactivity.
--
-- From a business perspective, this type of analysis could help identify
-- customer groups for retention analysis, re-engagement campaigns, or
-- additional investigation into purchasing behavior.


-- Important:
-- This query does NOT prove that a customer has permanently stopped purchasing
-- or has been lost as a customer.
--
-- It only identifies customers who meet the inactivity rule established
-- for this analysis:
--
-- More than 180 days since their most recent purchase.
--
-- Therefore, terms such as "potentially inactive" or "inactive based on the
-- 180-day threshold" are more accurate than stating that these customers
-- have definitely been lost.


-- Why 2026-06-01 Is Used Instead of Today's Date:
--
-- The dataset's latest OrderDate is 2026-06-01.
--
-- If CURRENT_DATE() were used while analyzing a historical or static dataset,
-- every customer's inactivity period would continue increasing even though
-- the dataset itself contains no newer transactions.
--
-- Using the maximum date represented in the dataset creates a fairer comparison:
--
-- "How long had this customer been inactive as of the end of the available data?"
--
-- rather than:
--
-- "How long has it been since their purchase compared with today's real-world date?"
-- =================================================================================================



