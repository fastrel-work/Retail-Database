JOIN catagories AS c
    ON c.Catagory_ID = p.Catagory_ID

    -- Connects each product to its corresponding category using Catagory_ID.
    --
    -- products.Catagory_ID identifies the category assigned to each product.
    -- catagories.Catagory_ID identifies that category in the catagories table.
    --
    -- This second JOIN allows SQL to retrieve CatagoryName for each product.
    --
    -- SQL can now follow the complete relationship:
    --
    -- order_details → products → catagories
    
GROUP BY c.CatagoryName

    -- GROUP BY places all records associated with the same product category
    -- into one group.
    --
    -- SUM(...) then calculates total profit separately for each category.
    --
    -- Unlike Problem 4, where profit was grouped by individual product,
    -- this query combines the profits of ALL products belonging to the
    -- same category.
    


ORDER BY total_profit DESC;

    -- ORDER BY sorts the completed category-level results using total_profit.
    --
    -- DESC means descending order, so the category generating the highest
    -- total profit appears first.
    --
    -- The remaining categories are then ranked from highest to lowest profit.


-- Final Result:
-- The query returns one row for each product category and ranks the categories
-- according to the total profit generated.



-- Interpretation:
-- Meat & Poultry generated the highest total product-level gross profit in the
-- dataset at approximately $77,308.34.
--
-- Grouping profit by category provides a broader view of product performance than
-- analyzing individual products alone. This can help identify which areas of the
-- company's product catalog contribute the most gross profit.


-- Important:
-- The products table is essential to this query because order_details does not
-- contain Catagory_ID or CatagoryName.
--
-- Therefore, SQL cannot directly connect:
--
-- order_details → catagories
--
-- Instead, products acts as the bridge:
--
-- order_details → products → catagories
--
