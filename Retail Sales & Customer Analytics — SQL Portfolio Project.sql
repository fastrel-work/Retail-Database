-- Problem 6: Identify the Products With the Highest Return Rates
-- Business Question:
-- Which products have the highest percentage of order-detail records marked as returned?
--
-- Goal:
-- Count the total number of order-detail records for each product, determine how many
-- of those records were returned, calculate the return rate as a percentage, and rank
-- products from highest to lowest return rate.
--
-- Return Rate Formula:
--
--                         Number of Returned Records
-- Return Rate (%) =     ----------------------------- × 100
--                         Total Order-Detail Records
--
-- In this dataset:
--
-- IsReturned = 1  →  The order-detail record was returned.
-- IsReturned = 0  →  The order-detail record was not returned.



SELECT
    od.Product_ID,

    -- Retrieves the Product_ID associated with each group of order-detail records.
    --
    -- The "od." prefix specifies that Product_ID is being retrieved from the
    -- order_details table.


    p.ProductName,

    -- Retrieves the corresponding product name from the products table.
    --
    -- Including ProductName makes the final results easier to understand than
    -- displaying only the Product_ID.


    COUNT(*) AS total_records,

    -- COUNT(*) counts the total number of order-detail records associated
    -- with each product.
    --
    -- Because the query is grouped by product later, COUNT(*) is calculated
    -- separately for each product.


    SUM(
        CASE
            WHEN od.IsReturned = 1 THEN 1
            ELSE 0
        END
    ) AS total_returns,

    -- CASE allows SQL to perform conditional logic on each record.
    --
    -- For every order-detail record, SQL checks the IsReturned column:
    --
    -- WHEN IsReturned = 1 THEN 1
    --     If the record was returned, assign it a value of 1.
    --
    -- ELSE 0
    --     If the record was not returned, assign it a value of 0.
    --
    -- SUM(...) then adds those values:
    --
    -- 0 + 1 + 0 + 1 + 1 = 3 returns
    --
    -- This allows the query to count only the records where IsReturned = 1.
    --
    -- AS total_returns assigns a descriptive alias to the calculated column.


    ROUND(
        SUM(
            CASE
                WHEN od.IsReturned = 1 THEN 1
                ELSE 0
            END
        )
        / COUNT(*) * 100,
        2
    ) AS return_rate

    -- This calculation converts the number of returned records into a percentage.
    --
    -- The numerator:
    --
    -- SUM(CASE WHEN IsReturned = 1 THEN 1 ELSE 0 END)
    --
    -- counts how many records for the product were returned.
    --
    -- The denominator:
    --
    -- COUNT(*)
    --
    -- counts the total number of order-detail records for that product.
    --
    -- Dividing total returns by total records gives the proportion of records
    -- that were returned.
   --
    -- Multiplying by 100 converts the decimal proportion into a percentage:
    --
    -- ROUND(..., 2) rounds the final return rate to two decimal places.
    --
    -- AS return_rate assigns a descriptive alias to the calculated percentage.


FROM order_details AS od

    -- Begins with the order_details table because it contains Product_ID
    -- and the IsReturned indicator needed for the return analysis.
    --
    -- AS od assigns "od" as a temporary alias for order_details.


JOIN products AS p
    ON od.Product_ID = p.Product_ID

    -- Connects each order-detail record to its corresponding product using Product_ID.
    --
    -- This JOIN allows the ProductName from the products table to be displayed
    -- alongside the return information stored in order_details.


GROUP BY od.Product_ID, p.ProductName

    -- GROUP BY places all order-detail records belonging to the same product
    -- into one group.
    --
    -- COUNT(*) and SUM(CASE...) are then calculated separately for each product.
    --


ORDER BY return_rate DESC;

    -- ORDER BY sorts the completed results using the calculated return_rate.
    --
    -- DESC means descending order, so products with the highest return rates
    -- appear at the top of the result set.
    --
    -- This makes products with unusually high return rates easier to identify
    -- for further investigation.


-- Interpretation:
-- Products appearing near the top of the result have a larger percentage of their
-- order-detail records marked as returned.
--
-- A high return rate can be useful as an indicator for further investigation into
-- areas such as product quality, customer expectations, product descriptions,
-- fulfillment issues, or other possible causes.
--
-- However, this query identifies the return pattern; it does not determine WHY
-- customers returned a product.


-- Important:
-- This query calculates a RECORD-LEVEL return rate rather than a UNIT-LEVEL return rate.
--
-- COUNT(*) counts order-detail records, not the total Quantity of products purchased.
--

