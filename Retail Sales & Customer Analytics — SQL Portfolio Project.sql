-- Business Question:
-- How much sales revenue did the company generate before accounting for discounts?
--
-- Goal:
-- Calculate the total gross revenue generated across all order-detail records.
--
-- Revenue Formula:
-- Revenue per line item = Quantity × UnitPrice
--
-- Because the goal is to calculate revenue BEFORE discounts, DiscountRate is not included
-- in this calculation.



SELECT
    SUM(Quantity * UnitPrice) AS total_revenue
    -- Quantity * UnitPrice calculates the gross revenue generated by each order-detail record.
    --
    -- For example:
    -- If Quantity = 3 and UnitPrice = $10.00:
    --
    -- 3 × $10.00 = $30.00 in gross revenue
    --
    -- SUM(...) then adds the revenue from every order-detail record together to calculate
    -- the company's total gross sales revenue.
    --
    -- AS total_revenue assigns a descriptive alias to the calculated output column.

FROM order_details;
    -- Specifies that Quantity and UnitPrice are retrieved from the order_details table.


-- Final Result:
-- Total Gross Revenue = $791,932.47
--
-- Interpretation:
-- The company generated $791,932.47 in gross sales revenue across all order-detail
-- records before accounting for customer discounts.
--
-- Important:
-- Revenue is not the same as profit. This calculation measures the value of sales
-- before discounts and does not subtract product costs or other business expenses.

