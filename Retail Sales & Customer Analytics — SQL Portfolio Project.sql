-- =================================================================================================
-- Problem 2B: Calculate Total Revenue After Discounts
-- Business Question:
-- How much sales revenue did the company actually generate after accounting for discounts?
--
-- Goal:
-- Calculate gross sales revenue and subtract the total dollar amount given to customers
-- through discounts.
--
-- Formula:
-- Revenue After Discounts = Gross Revenue - Total Discount Amount
--
-- Gross Revenue         = Quantity × UnitPrice
-- Total Discount Amount = Quantity × UnitPrice × DiscountRate



SELECT
    SUM(Quantity * UnitPrice)
    -
    SUM(Quantity * UnitPrice * DiscountRate)
    AS total_revenue_after_discounts

    -- SUM(Quantity * UnitPrice) calculates the company's total gross revenue before
    -- any discounts are applied.
    --
    -- SUM(Quantity * UnitPrice * DiscountRate) calculates the total dollar amount
    -- deducted from sales because of discounts.
    --
    -- The query subtracts the discount amount from gross revenue:
    --
    -- SUM() performs these calculations across all order-detail records.
    --
    -- AS total_revenue_after_discounts assigns a descriptive alias to the
    -- final calculated output column.

FROM order_details;
    -- Specifies that Quantity, UnitPrice, and DiscountRate are retrieved
    -- from the order_details table.


-- Final Result:
-- Total Revenue After Discounts = $761,951.13
--
-- Interpretation:
-- After accounting for customer discounts, the company generated approximately
-- $761,951.13 in sales revenue.
--
-- Compared with the gross revenue calculated in Problem 2A:
--
-- Gross Revenue:                    $791,932.47
-- Revenue After Discounts:          $761,951.13
-- Difference Due to Discounts:       $29,981.34
--
-- Important:
-- This calculation accounts for discounts, but it still represents revenue rather
-- than profit. Product costs and other business expenses have not been subtracted.
